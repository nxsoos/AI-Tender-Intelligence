export const dictionaries: Record<Locale, Dictionary> = { en, ar };
export type TranslationKey = keyof Dictionary;
export function localized(
  value: string | { en: string; ar: string } | null | undefined,
  locale: Locale,
): string {
  return typeof value === "string" ? value : value?.[locale] || value?.en || "";
}
export function formatNumber(value: number, locale: Locale) {
  return new Intl.NumberFormat(locale === "ar" ? "ar-SA" : "en-GB", {
    numberingSystem: "latn",
  }).format(value);
}
export function formatDate(
  value: string | null | undefined,
  locale: Locale,
  options?: Intl.DateTimeFormatOptions,
) {
  if (!value) return dictionaries[locale].notFound;
  const date = new Date(
    /^\d{4}-\d{2}-\d{2}$/.test(value) ? `${value}T12:00:00Z` : value,
  );
  if (Number.isNaN(date.getTime())) return value;
  return new Intl.DateTimeFormat(
    locale === "ar" ? "ar-SA-u-ca-gregory-nu-latn" : "en-GB",
    { day: "numeric", month: "short", year: "numeric", ...options },
  ).format(date);
}
